#!/usr/bin/env node
/**
 * Generate Supabase TypeScript types from the linked project.
 * Run: npm run gen:types (requires Supabase project linked: npx supabase link).
 * Output: src/types/supabase.ts
 */
import { execSync } from "child_process";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const outPath = path.join(root, "src", "types", "supabase.ts");

try {
  const out = execSync("npx supabase gen types typescript", {
    cwd: root,
    encoding: "utf-8",
    stdio: ["pipe", "pipe", "pipe"],
  });
  const header = `// Generated by scripts/gen-supabase-types.mjs — do not edit by hand.\n// Run: npm run gen:types (requires \`supabase link\`).\n\n`;
  writeFileSync(outPath, header + out, "utf-8");
  console.log("Wrote", outPath);
} catch (err) {
  console.error(
    "gen:types failed. Ensure Supabase project is linked: npx supabase link --project-ref <ref>",
  );
  if (err.stderr) process.stderr.write(err.stderr);
  process.exit(1);
}
