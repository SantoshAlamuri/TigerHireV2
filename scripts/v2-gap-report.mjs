#!/usr/bin/env node
/**
 * Prints — and writes — an honest report of how far the v2 build is from the
 * approved design.
 *
 * Same extraction as tests/unit/v2-spec-conformance.test.ts: requirements come
 * out of the pinned artifact, not from anybody's memory. This exists so the gap
 * can be READ, by anyone, without running a test suite or asking me.
 *
 *   node scripts/v2-gap-report.mjs          → print
 *   node scripts/v2-gap-report.mjs --write  → also update docs/v2-design-gaps.md
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import {
  readSpec,
  screenKeys,
  screenBody,
  requiredLabels,
  builtText,
  normalizeForMatch,
  MANIFEST,
} from "./v2-spec-extract.mjs";

const ROOT = process.cwd();
const APP = join(ROOT, "src/app/(dashboard)/recruit/v2");
const LIB = join(ROOT, "src/lib/v2");
const SRC = join(ROOT, "src");
const OUT = join(ROOT, "docs/v2-design-gaps.md");

const PARKED = new Set(["cd:status", "cd:data"]);

const spec = readSpec(ROOT);

const allKeys = screenKeys(spec);
const unbuilt = allKeys.filter((k) => !PARKED.has(k) && !MANIFEST[k]);

const byScreen = new Map();
for (const [key, files] of Object.entries(MANIFEST)) {
  const body = screenBody(spec, key);
  if (!body) continue;
  const built = normalizeForMatch(builtText(APP, LIB, files, SRC));
  const missing = requiredLabels(body).filter(
    (l) => !built.includes(normalizeForMatch(l.label).trim()),
  );
  if (missing.length) byScreen.set(key, missing);
}

const totalLabels = [...byScreen.values()].reduce((n, v) => n + v.length, 0);
const built = allKeys.length - unbuilt.length - PARKED.size;

const lines = [];
lines.push("# v2 — how far the build is from the approved design");
lines.push("");
lines.push("Generated by `node scripts/v2-gap-report.mjs`. Requirements are extracted from the");
lines.push("pinned artifact at `tests/fixtures/approved-ui-spec.html` — not written by hand, so");
lines.push("this cannot flatter the build.");
lines.push("");
lines.push("| | |");
lines.push("|---|---|");
lines.push(`| Screens in the approved design | **${allKeys.length}** |`);
lines.push(`| Built | **${built}** |`);
lines.push(`| Not built | **${unbuilt.length}** |`);
lines.push(`| Parked by the operator | ${PARKED.size} (candidate portal) |`);
lines.push(`| Labels the design shows that the build does not | **${totalLabels}** |`);
lines.push("");
lines.push("## Screens with no build at all");
lines.push("");
if (unbuilt.length === 0) lines.push("_None._");
for (const k of unbuilt) lines.push(`- \`${k}\``);
lines.push("");
lines.push("## Built, but missing pieces the design calls for");
lines.push("");
if (byScreen.size === 0) lines.push("_None._");
for (const [k, missing] of [...byScreen].sort()) {
  lines.push(`**\`${k}\`** — ${missing.length} missing`);
  for (const m of missing.sort((x, y) => x.label.localeCompare(y.label)))
    lines.push(`- ${m.label} _(${m.kind})_`);
  lines.push("");
}

const report = lines.join("\n") + "\n";
process.stdout.write(report);

if (process.argv.includes("--write")) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, report);
  process.stderr.write(`\nwritten: ${OUT}\n`);
}
